// φίλτρο δεν είναι ούτως ή άλλως security-grade (βλ. σχόλιο στην κορυφή του
// αρχείου), προτιμάμε να χάσουμε μερικά σπάνια edge cases παρά να
// μπλοκάρουμε κόσμο από το πραγματικό του όνομα.
