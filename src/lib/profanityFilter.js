function normalize(str) {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // αφαίρεση τόνων (ά -> α, κ.λπ.) - explicit \uXXXX range αντί για raw Unicode χαρακτήρες (πιο σταθερό cross-browser/engine)
    .replace(/[^a-zα-ω]/g, ''); // κρατάμε μόνο γράμματα - πιάνει και "μ α λ α κ α ς" ή "μ.α.λ-α.κ.α.σ"
}

export function containsProfanity(text) {
  if (!text) return false;
  const normalized = normalize(text);
  if (!normalized) return false;
  if (SAFELIST.some((word) => normalized.includes(word))) return false;
  return BLOCKLIST.some((word) => normalized.includes(word));
}